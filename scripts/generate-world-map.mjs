#!/usr/bin/env node
/*
 * Regenerates _includes/world-map.svg — the land outlines the visitor map is
 * drawn on. Only needs rerunning if you want a different projection, a
 * different level of detail, or Antarctica back.
 *
 * The projection is an exact plate carrée so that _data/visitors.json can turn
 * a lat/lon straight into viewBox coordinates with plain arithmetic:
 *   x = (lon + 180) / 360 * 1000      y = (90 - lat) / 180 * 500
 * scripts/update-visitors.mjs relies on that; keep the two in sync.
 *
 * Usage:
 *   npm i --no-save d3-geo topojson-client topojson-simplify
 *   curl -o /tmp/countries-110m.json https://cdn.jsdelivr.net/npm/world-atlas@2/countries-110m.json
 *   node scripts/generate-world-map.mjs /tmp/countries-110m.json
 *
 * Source data: world-atlas@2 countries-110m (Natural Earth, public domain).
 */

import fs from 'node:fs';
import path from 'node:path';
import { geoEquirectangular, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';
import { presimplify, simplify, filter, filterWeight } from 'topojson-simplify';

const MAP_W = 1000;
const MAP_H = 500;
// Chosen by eye: small enough to keep New Zealand, Japan and the UK legible,
// aggressive enough to keep the inlined path around 30 KB.
const EPSILON = 0.8;

const input = process.argv[2];
if (!input) {
  console.error('usage: node scripts/generate-world-map.mjs <countries-110m.json>');
  process.exit(1);
}

const projection = geoEquirectangular()
  .scale(MAP_W / (2 * Math.PI))
  .translate([MAP_W / 2, MAP_H / 2]);

let topology = presimplify(JSON.parse(fs.readFileSync(input, 'utf8')));
topology = simplify(topology, EPSILON);
topology = filter(topology, filterWeight(topology, EPSILON));

const countries = feature(topology, topology.objects.countries).features
  .filter((f) => f.id !== '010'); // Antarctica — nothing to show, lots of pixels

const d = countries.map((f) => geoPath(projection).digits(1)(f)).filter(Boolean).join('');

const out = path.join(import.meta.dirname, '..', '_includes', 'world-map.svg');
fs.writeFileSync(
  out,
  `<!-- World land outlines. Generated by scripts/generate-world-map.mjs — do not edit by hand.
     Source: world-atlas@2 countries-110m (Natural Earth, public domain), simplified
     at eps=${EPSILON}, Antarctica removed.
     Equirectangular (plate carrée): lon -180..180 -> x 0..${MAP_W}; lat 90..-90 -> y 0..${MAP_H}. -->
<path class="vmap__land" d="${d}"/>
`,
);
console.log(`wrote ${out} (${d.length} chars of path data, ${countries.length} features)`);
